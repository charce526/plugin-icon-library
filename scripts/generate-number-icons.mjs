/**
 * 从开源图标库 Material Design Icons (@mdi/js) 生成数字序号图标数据。
 *
 * 用法：
 *   node scripts/generate-number-icons.mjs            # 生成 src/client/number-icons.generated.ts
 *   node scripts/generate-number-icons.mjs --report   # 只打印将生成的图标清单
 *
 * 说明：
 * - lucide 没有数字图标，之前自绘的数字看不清，改为使用 MDI 现成的数字图标；
 * - 数据来源：@mdi/js（Apache-2.0，https://github.com/Templarian/MaterialDesign-JS）；
 * - 优先使用本地 node_modules 里的 @mdi/js，没有则用 npm pack 下载到系统临时目录解压读取；
 * - 生成后图标数据内嵌到源码里，运行时不依赖 @mdi/js。
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MDI_PACKAGE = process.env.MDI_PACKAGE || '@mdi/js@7.4.47';
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const pluginDir = path.resolve(scriptDir, '..');
const outFile = path.join(pluginDir, 'src', 'client', 'number-icons.generated.ts');
const reportOnly = process.argv.includes('--report');

/** 数字范围：MDI 只提供 0~10 的单个数字图标 */
const NUMBERS = Array.from({ length: 11 }, (_, index) => index);
/** MDI 里每个数字的几种样式 */
const VARIANTS = [
  { suffix: '', mdi: '' },
  { suffix: 'Circle', mdi: 'Circle' },
  { suffix: 'CircleOutline', mdi: 'CircleOutline' },
  { suffix: 'Box', mdi: 'Box' },
  { suffix: 'BoxOutline', mdi: 'BoxOutline' },
];

/** 目标图标：本地名 -> MDI 图标名 */
const targets = [];
for (const value of NUMBERS) {
  for (const variant of VARIANTS) {
    targets.push({
      name: `Number${value}${variant.suffix}`,
      mdiName: `Numeric${value}${variant.mdi}`,
    });
  }
}

function findInstalledMdi() {
  const candidates = [
    path.resolve(pluginDir, 'node_modules', '@mdi', 'js', 'mdi.js'),
    path.resolve(pluginDir, '..', '..', '..', '..', 'node_modules', '@mdi', 'js', 'mdi.js'),
  ];
  return candidates.find((file) => fs.existsSync(file)) || null;
}

function readMdiSource() {
  const installed = findInstalledMdi();
  if (installed) {
    console.log(`使用本地 @mdi/js：${installed}`);
    return fs.readFileSync(installed, 'utf8');
  }

  const cacheDir = path.join(os.tmpdir(), 'nocobase-icon-library-mdi');
  const mdiJsPath = path.join(cacheDir, 'package', 'mdi.js');
  if (fs.existsSync(mdiJsPath)) {
    console.log(`使用缓存：${mdiJsPath}`);
    return fs.readFileSync(mdiJsPath, 'utf8');
  }

  fs.mkdirSync(cacheDir, { recursive: true });
  console.log(`本地没有 @mdi/js，正在下载 ${MDI_PACKAGE} ...`);
  const tarball = execSync(`npm pack ${MDI_PACKAGE} --silent`, { cwd: cacheDir, encoding: 'utf8' })
    .trim()
    .split('\n')
    .pop()
    .trim();
  execSync(`tar -xzf "${tarball}" -C "${cacheDir}"`, { cwd: cacheDir, stdio: 'inherit' });
  if (!fs.existsSync(mdiJsPath)) {
    throw new Error(`解压后未找到 mdi.js：${mdiJsPath}`);
  }
  return fs.readFileSync(mdiJsPath, 'utf8');
}

const source = readMdiSource();
const version = (source.match(/Material Design Icons v([\d.]+)/) || [])[1] || 'unknown';

const icons = {};
const missing = [];
for (const target of targets) {
  const match = source.match(new RegExp(`\\bmdi${target.mdiName}\\s*=\\s*"([^"]+)"`));
  if (!match) {
    missing.push(target.mdiName);
    continue;
  }
  icons[target.name] = match[1];
}

console.log(`MDI 版本：${version}`);
console.log(`请求数字图标：${targets.length}，命中：${Object.keys(icons).length}`);
if (missing.length) {
  console.log(`未找到：${missing.join(', ')}`);
}
console.log(`示例：${Object.keys(icons).slice(0, 8).join(', ')}`);

if (reportOnly) {
  process.exit(0);
}

const body = Object.entries(icons)
  .map(([name, d]) => `  ${name}: '${d}',`)
  .join('\n');

const content = `/**
 * AUTO-GENERATED by scripts/generate-number-icons.mjs — 请勿手动修改。
 *
 * 数字序号图标数据，来源：Material Design Icons (@mdi/js v${version})，Apache-2.0
 * https://github.com/Templarian/MaterialDesign-JS
 * 重新生成：node scripts/generate-number-icons.mjs
 */
export const numberIconPaths: Record<string, string> = {
${body}
};
`;

fs.writeFileSync(outFile, content, 'utf8');
console.log(`已写入 ${path.relative(process.cwd(), outFile)}`);
