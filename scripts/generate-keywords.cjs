// Generate exact-name translations. Unknown vocabulary fails instead of guessing a category.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const glossaryEntries = fs.readFileSync(path.join(__dirname, 'keyword-glossary.txt'), 'utf8').trim().split(/\s+/);
for (const entry of glossaryEntries) {
  if (!/^[A-Za-z0-9]+=[^=]+$/.test(entry)) throw new Error('Invalid glossary entry: ' + entry);
}
const glossary = Object.fromEntries(glossaryEntries.map(entry => entry.split('=')));
if (Object.keys(glossary).length !== glossaryEntries.length) throw new Error('Duplicate glossary keys');
const overrides = require('./keyword-overrides.json');
const nativeNames = Object.keys(require('@ant-design/icons')).filter(name => /(Outlined|Filled|TwoTone)$/.test(name))
  .map(name => name.replace(/(Outlined|Filled|TwoTone)$/, ''));
const numberNames = [...fs.readFileSync(path.join(root, 'src/client/number-icons.generated.ts'), 'utf8')
  .matchAll(/^\s+(Number\w+):/gm)].map(match => match[1]);
const names = [...new Set([...require('./icon-manifest.json'), ...nativeNames, ...numberNames])].sort();
const missing = new Set();
function translate(name) {
  if (overrides[name]) return overrides[name];
  if (/^Clock\d+$/.test(name)) return `${name.slice(5)}点时钟`;
  if (/^Heading\d+$/.test(name)) return `${name.slice(7)}级标题`;
  if (/^Columns\d+$/.test(name)) return `${name.slice(7)}列布局`;
  if (/^Rows\d+$/.test(name)) return `${name.slice(4)}行布局`;
  const tokens = name.match(/[A-Z]+(?=[A-Z][a-z]|$)|[A-Z]?[a-z]+|[0-9]+/g) || [];
  let text = '';
  for (let start = 0; start < tokens.length;) {
    let end = tokens.length;
    while (end > start && !glossary[tokens.slice(start, end).join('')]) end--;
    if (end > start) { text += glossary[tokens.slice(start, end).join('')]; start = end; }
    else { const word = tokens[start++]; if (/^\d+$/.test(word)) text += word; else missing.add(word); }
  }
  return text;
}
const translations = Object.fromEntries(names.map(name => [name.toLowerCase(), translate(name)]));
if (missing.size) throw new Error('Missing direct translations: ' + [...missing].sort().join(' '));
for (const name of names) {
  if (!/[\u4e00-\u9fff]/.test(translations[name.toLowerCase()])) throw new Error('Missing Chinese translation: ' + name);
}
const output = '/** Generated by scripts/generate-keywords.cjs. Exact raw-name lookup; no category or prefix fallback. */\n'
  + 'export const iconKeywords: Record<string, string> = ' + JSON.stringify(translations, null, 2) + ';\n';
const target = path.join(root, 'src/client-v2/iconKeywords.ts');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Icon translations are stale');
} else fs.writeFileSync(target, output);
console.log(`Exact Chinese translations: ${names.length} names, ${nativeNames.length} native variants, ${numberNames.length} number icons; no untranslated names`);
